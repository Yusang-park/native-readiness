import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { withViteCompat } from './metro.js';
import type { ViteDevServerShim } from './vite/plugins.js';

const appRoot = '/repo/native';

describe('withViteCompat', () => {
  it('watches the web root and the library itself, so a linked copy can be bundled', () => {
    const config = withViteCompat({ projectRoot: appRoot, watchFolders: [] }, { root: '..', pregenerate: false });
    const libraryRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
    expect(config.watchFolders).toEqual(['/repo', libraryRoot]);
  });

  it('leaves the server root alone so the native entry keeps resolving', () => {
    const config = withViteCompat({ projectRoot: appRoot, server: { port: 8081 } }, { root: '..', pregenerate: false });
    expect(config.server).toEqual({ port: 8081 });
  });

  it('blocks ignored web-root folders from crawling', () => {
    const config = withViteCompat({ projectRoot: appRoot }, { root: '..', ignore: ['amplify'], pregenerate: false });
    const [rule] = [config.resolver?.blockList].flat();
    expect(rule?.test(path.join('/repo', 'amplify', 'backend', 'x.js'))).toBe(true);
    expect(rule?.test(path.join('/repo', 'src', 'amplify.ts'))).toBe(false);
  });

  it('keeps existing block rules', () => {
    const config = withViteCompat({ projectRoot: appRoot, resolver: { blockList: /keep/ } }, { root: '..', ignore: ['build'], pregenerate: false });
    expect([config.resolver?.blockList].flat()).toHaveLength(2);
  });

  it('serves static web folders through Metro middleware before Metro handles the request', async () => {
    const fixture = path.join(path.dirname(new URL(import.meta.url).pathname), '../test/fixtures/vite-app');
    const config = withViteCompat(
      { projectRoot: path.join(fixture, 'native') },
      { root: '..', staticDirs: { '/lang': 'lang' }, pregenerate: false },
    );
    const enhance = config.server?.enhanceMiddleware;
    expect(typeof enhance).toBe('function');
    const send = (url: string) =>
      new Promise<string>((resolve) => {
        const middleware = enhance?.(() => resolve('metro'), {});
        middleware?.({ url, method: 'GET' }, { statusCode: 0, setHeader: () => undefined, end: (b?: string | Buffer) => resolve(String(b)) }, () => resolve('next'));
      });
    expect(await send('/lang/en.json')).toContain('Hello');
    expect(await send('/index.bundle')).toBe('metro');
  });

  it("serves files generated by Vite plugins' dev middleware", async () => {
    const plugin = {
      configureServer(server: ViteDevServerShim) {
        server.middlewares.use((req, res, next) => (req.url === '/generated.html' ? res.end('generated') : next()));
      },
    };
    const config = withViteCompat({ projectRoot: appRoot }, { root: '..', vitePlugins: [plugin], pregenerate: false });
    const body = await new Promise<string>((resolve) => {
      const middleware = config.server?.enhanceMiddleware?.(() => resolve('metro'), {});
      middleware?.({ url: '/generated.html', method: 'GET' }, { statusCode: 0, setHeader: () => undefined, end: (b?: string | Buffer) => resolve(String(b)) }, () => resolve('next'));
    });
    expect(body).toBe('generated');
  });
});
